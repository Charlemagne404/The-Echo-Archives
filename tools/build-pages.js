function resolveCleanRouteAlias(entry) {
  if (!entry?.canonicalUrl) {
    return null;
  }

  let pathname = "";
  try {
    pathname = new URL(entry.canonicalUrl, DEFAULT_SITE_URL).pathname || "";
  } catch (_error) {
    return null;
  }

  if (!pathname || pathname === "/" || pathname.endsWith(".html")) {
    return null;
  }

  return pathname.replace(/^\/+/, "");
}

function shouldNoIndexAlias(cleanRouteAlias) {
  return NOINDEX_ALIAS_PATHS.has(cleanRouteAlias);
}

function resolveSiteUrl(manifest) {
  const configured = String(process.env.SITE_URL || "").trim();
  if (configured) {
    try {
      return new URL(configured).origin;
    } catch (_error) {
      throw new Error(`SITE_URL must be a valid absolute URL. Received: ${configured}`);
    }
  }

  const homeEntry = Array.isArray(manifest) ? manifest.find((entry) => entry.output === "index.html") : null;
  if (!homeEntry?.canonicalUrl) {
    return DEFAULT_SITE_URL;
  }

  try {
    return new URL(homeEntry.canonicalUrl).origin;
  } catch (_error) {
    return DEFAULT_SITE_URL;
  }
}

function resolveManifestCanonicalUrls(manifest, siteUrl) {
  return manifest.map((entry) => {
    let sourceUrl;
    try {
      sourceUrl = new URL(entry.canonicalUrl, `${siteUrl}/`);
    } catch (_error) {
      throw new Error(`Invalid canonical URL in page manifest for ${entry.output}: ${entry.canonicalUrl}`);
    }

    return {
      ...entry,
      canonicalUrl: new URL(`${sourceUrl.pathname}${sourceUrl.search}`, `${siteUrl}/`).toString(),
    };
  });
}

