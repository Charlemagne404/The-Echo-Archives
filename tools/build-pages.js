const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const SITE_SRC = path.join(ROOT, "site-src");
const PARTIALS_DIR = path.join(SITE_SRC, "partials");
const PAGES_DIR = path.join(SITE_SRC, "pages");
const MANIFEST_PATH = path.join(SITE_SRC, "page-manifest.json");
const GENERATED_BANNER = "<!-- Generated from site-src by tools/build-pages.js. Do not edit this file directly. -->";

function readFile(filePath) {
  return fs.readFileSync(filePath, "utf8");
}

function writeFile(filePath, contents) {
  fs.writeFileSync(filePath, contents);
}

function renderTemplate(template, replacements) {
  return template.replace(/\{\{([a-zA-Z0-9]+)\}\}/g, (_match, key) => replacements[key] ?? "");
}

function renderStylesheets(extraStylesheets = []) {
  return [
    '<link rel="stylesheet" href="style.css?v=12" />',
    '<link rel="stylesheet" href="home.css?v=28" />',
    ...extraStylesheets.map((href) => `<link rel="stylesheet" href="${href}" />`),
  ].join("\n");
}

function renderNavLinks(activeNav) {
  const navItems = [
    { id: "browse", label: "Browse", href: "/index.html" },
    { id: "collections", label: "Collections", href: "/collections.html" },
    { id: "about", label: "About", href: "/about.html" },
    { id: "submit", label: "Submit", href: "/submit.html" },
    { id: "for-creators", label: "For creators", href: "/for-creators.html" },
  ];

  return navItems
    .map((item) => {
      const activeClass = item.id === activeNav ? ' class="is-active"' : "";
      return `<a${activeClass} href="${item.href}">${item.label}</a>`;
    })
    .join("\n    ");
}

function renderPage(entry, partials) {
  const headMarkup = renderTemplate(partials.head, {
    title: entry.title,
    description: entry.description,
    canonicalUrl: entry.canonicalUrl,
    stylesheets: renderStylesheets(entry.extraStylesheets),
  });
  const headerMarkup = renderTemplate(partials.header, {
    navLinks: renderNavLinks(entry.activeNav),
  });
  const pageBody = readFile(path.join(PAGES_DIR, entry.source)).trim();
  const bodySections = [
    headerMarkup,
    entry.includeChatShell ? partials.chatShell : "",
    pageBody,
    entry.includeFloatingControls ? partials.floatingControls : "",
    partials.footer,
    '  <script src="shared/archive-record.js?v=1"></script>',
    '  <script src="shared/archive-search.js?v=1"></script>',
    '  <script type="module" src="script.js?v=22"></script>',
  ]
    .filter(Boolean)
    .join("\n\n");

  return [
    "<!DOCTYPE html>",
    GENERATED_BANNER,
    '<html lang="en">',
    "<head>",
    headMarkup,
    "</head>",
    `<body class="${entry.bodyClass}">`,
    bodySections,
    "</body>",
    "</html>",
    "",
  ].join("\n");
}

function main() {
  const manifest = JSON.parse(readFile(MANIFEST_PATH));
  const partials = {
    head: readFile(path.join(PARTIALS_DIR, "head.html")).trim(),
    header: readFile(path.join(PARTIALS_DIR, "header.html")).trim(),
    chatShell: readFile(path.join(PARTIALS_DIR, "chat-shell.html")).trim(),
    floatingControls: readFile(path.join(PARTIALS_DIR, "floating-controls.html")).trim(),
    footer: readFile(path.join(PARTIALS_DIR, "footer.html")).trim(),
  };

  manifest.forEach((entry) => {
    const outputPath = path.join(ROOT, entry.output);
    writeFile(outputPath, renderPage(entry, partials));
  });
}

main();
