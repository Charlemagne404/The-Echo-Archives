function readFile(filePath) {
  return fs.readFileSync(filePath, "utf8");
}

function writeFile(filePath, contents) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, String(contents).replace(/[ \t]+$/gm, ""));
}

function rewriteCssAssetUrls(contents, sourcePath) {
  return contents.replace(/url\(\s*(["']?)([^"')]+)\1\s*\)/gi, (match, quote, rawValue) => {
    const value = String(rawValue || "").trim();
    if (!value || /^(?:[a-z]+:|\/\/|\/|#)/i.test(value)) {
      return match;
    }

    const suffixIndex = value.search(/[?#]/);
    const pathname = suffixIndex >= 0 ? value.slice(0, suffixIndex) : value;
    const suffix = suffixIndex >= 0 ? value.slice(suffixIndex) : "";
    const resolvedPath = path.resolve(path.dirname(sourcePath), pathname);
    const relativePath = path.relative(ROOT, resolvedPath);
    if (relativePath.startsWith("..") || path.isAbsolute(relativePath)) {
      throw new Error(`CSS asset escapes the public root: ${value} in ${path.relative(ROOT, sourcePath)}`);
    }

    const publicUrl = `/${relativePath.split(path.sep).join("/")}${suffix}`;
    const renderedQuote = quote || '"';
    return `url(${renderedQuote}${publicUrl}${renderedQuote})`;
  });
}

function flattenCssFile(filePath, ancestry = []) {
  const normalizedPath = path.resolve(filePath);
  if (ancestry.includes(normalizedPath)) {
    const cycle = [...ancestry, normalizedPath].map((entry) => path.relative(ROOT, entry)).join(" -> ");
    throw new Error(`Circular CSS import detected: ${cycle}`);
  }

  const nextAncestry = [...ancestry, normalizedPath];
  const contents = readFile(normalizedPath);
  const flattened = contents.replace(
    /@import\s+(?:url\(\s*)?["']([^"']+)["']\s*\)?\s*;/gi,
    (_match, importValue) => {
      const relativeImport = stripQuery(importValue);
      if (/^(?:[a-z]+:|\/\/|\/)/i.test(relativeImport)) {
        throw new Error(`External or root CSS import cannot be flattened: ${importValue}`);
      }

      const importedPath = path.resolve(path.dirname(normalizedPath), relativeImport);
      return flattenCssFile(importedPath, nextAncestry);
    },
  );

  return [
    `/* Source: ${path.relative(ROOT, normalizedPath).split(path.sep).join("/")} */`,
    rewriteCssAssetUrls(flattened, normalizedPath).trim(),
  ].join("\n");
}

function renderCssBundle(relativePaths) {
  const contents = `${[
    GENERATED_CSS_BANNER,
    ...relativePaths.map((relativePath) => flattenCssFile(path.join(ROOT, relativePath))),
  ]
    .join("\n\n")
    .replace(/[ \t]+$/gm, "")
    .trimEnd()}\n`;

  if (/@import\b/i.test(contents)) {
    throw new Error("Generated CSS bundle still contains an @import rule.");
  }

  return contents;
}

function hashBuffer(buffer) {
  return crypto.createHash("sha1").update(buffer).digest("hex").slice(0, 10);
}

function listFilesDeep(startPath) {
  const results = [];

  if (!fs.existsSync(startPath)) {
    return results;
  }

  function walk(currentPath) {
    fs.readdirSync(currentPath, { withFileTypes: true }).forEach((entry) => {
      const absolutePath = path.join(currentPath, entry.name);
      if (entry.isDirectory()) {
        walk(absolutePath);
        return;
      }

      results.push(absolutePath);
    });
  }

  walk(startPath);
  return results.sort((left, right) => left.localeCompare(right));
}

function hashFile(relativePath) {
  return hashBuffer(fs.readFileSync(path.join(ROOT, relativePath)));
}

function hashTree(relativePath) {
  const files = listFilesDeep(path.join(ROOT, relativePath));
  const hash = crypto.createHash("sha1");

  files.forEach((filePath) => {
    hash.update(path.relative(ROOT, filePath));
    hash.update(fs.readFileSync(filePath));
  });

  return hash.digest("hex").slice(0, 10);
}

