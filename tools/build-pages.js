function serializeStructuredData(value) {
  return JSON.stringify(value)
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

function renderStructuredData(value) {
  if (!value) {
    return "";
  }
  return `<script id="pageStructuredData" type="application/ld+json">${serializeStructuredData(value)}</script>`;
}

