const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const SOFT_MAX_JS_LINES = 350;
const HARD_MAX_JS_LINES = 550;
const SOFT_MAX_CSS_LINES = 350;
const HARD_MAX_CSS_LINES = 550;
const GENERATED_BANNER = "<!-- Generated from site-src by tools/build-pages.js. Do not edit this file directly. -->";
const GENERATED_JS_BANNER = "// Generated from tools/build-pages.js. Do not edit this file directly.";
const GENERATED_CSS_BANNER = "/* Generated from tools/build-pages.js. Do not edit this file directly. */";
const ACTIVE_REFERENCE_EXTENSIONS = [".js", ".json", ".yml", ".yaml"];
const COVER_SOFT_MAX_BYTES = 500 * 1024;
const COVER_HARD_MAX_BYTES = 1.5 * 1024 * 1024;
const HERO_HARD_MAX_BYTES = 250 * 1024;

function listFiles(startDir, extension) {
  const results = [];

  if (!fs.existsSync(startDir)) {
    return results;
  }

  function walk(currentDir) {
    fs.readdirSync(currentDir, { withFileTypes: true }).forEach((entry) => {
      const absolutePath = path.join(currentDir, entry.name);
      if (entry.isDirectory()) {
        walk(absolutePath);
        return;
      }

      if (absolutePath.endsWith(extension)) {
        results.push(absolutePath);
      }
    });
  }

  walk(startDir);
  return results;
}

function getLineCount(filePath) {
  const contents = readFile(filePath);
  if (contents.length === 0) {
    return 0;
  }

  return contents.endsWith("\n")
    ? contents.slice(0, -1).split("\n").length
    : contents.split("\n").length;
}

function readFile(filePath) {
  return fs.readFileSync(filePath, "utf8");
}

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function warn(message) {
  console.warn(message);
}

function checkLineBudget(filePath, softLimit, hardLimit) {
  const lineCount = getLineCount(filePath);
  const relativePath = path.relative(ROOT, filePath);

  assert(lineCount <= hardLimit, `${relativePath} exceeds hard limit of ${hardLimit} lines (${lineCount}).`);

  if (lineCount > softLimit) {
    warn(`${relativePath} exceeds soft limit of ${softLimit} lines (${lineCount}).`);
  }
}

function checkLineBudgets() {
  const jsFiles = listFiles(path.join(ROOT, "shared", "app"), ".js");
  const cssFiles = listFiles(path.join(ROOT, "shared", "styles"), ".css");

  jsFiles.forEach((filePath) => {
    checkLineBudget(filePath, SOFT_MAX_JS_LINES, HARD_MAX_JS_LINES);
  });

  cssFiles.forEach((filePath) => {
    checkLineBudget(filePath, SOFT_MAX_CSS_LINES, HARD_MAX_CSS_LINES);
  });
}

function checkArchiveReferences() {
  const activeRoots = [
    path.join(ROOT, ".github"),
    path.join(ROOT, "backend"),
    path.join(ROOT, "shared"),
    path.join(ROOT, "tools"),
    path.join(ROOT, "site-src"),
  ];

  activeRoots.forEach((activeRoot) => {
    ACTIVE_REFERENCE_EXTENSIONS.forEach((extension) => {
      listFiles(activeRoot, extension).forEach((filePath) => {
        if (filePath === __filename) {
          return;
        }

        assert(
          !readFile(filePath).includes("docs/archive/"),
          `${path.relative(ROOT, filePath)} still references docs/archive/.`,
        );
      });
    });
  });

  assert(!fs.existsSync(path.join(ROOT, "docs", "archive", "legacy-redirects.json")), "Active redirect manifest still lives in docs/archive/.");
  assert(fs.existsSync(path.join(ROOT, "shared", "config", "legacy-redirects.json")), "shared/config/legacy-redirects.json is missing.");
}

function checkGeneratedPages() {
  const manifest = JSON.parse(readFile(path.join(ROOT, "site-src", "page-manifest.json")));

  manifest.forEach((entry) => {
    const pagePath = path.join(ROOT, entry.output);
    const pageMarkup = readFile(pagePath);
    assert(pageMarkup.includes(GENERATED_BANNER), `${entry.output} is missing the generated-file banner.`);
  });
}

function checkGeneratedAssets() {
  const jsAssets = ["script.js", "sw.js"].map((fileName) => readFile(path.join(ROOT, fileName)));
  const cssFileNames = [
    "style.css",
    "public-heroes.css",
    "home.css",
    "info.css",
    "collections.css",
    "creators.css",
    "submit.css",
    "maintainer.css",
    "detail.css",
    "chat.css",
  ];
  const cssAssets = cssFileNames.map((fileName) => readFile(path.join(ROOT, fileName)));

  jsAssets.forEach((contents, index) => {
    const fileName = ["script.js", "sw.js"][index];
    assert(contents.startsWith(GENERATED_JS_BANNER), `${fileName} is missing the generated-file banner.`);
  });
  cssAssets.forEach((contents, index) => {
    const fileName = cssFileNames[index];
    assert(contents.startsWith(GENERATED_CSS_BANNER), `${fileName} is missing the generated-file banner.`);
    assert(!/@import\s/i.test(contents), `${fileName} still contains render-blocking CSS imports.`);
  });
}

function checkImageBudgets() {
  const heroPath = path.join(ROOT, "images", "hero-archive-dish.webp");
  assert(fs.existsSync(heroPath), "The optimized homepage hero image is missing.");
  assert(fs.statSync(heroPath).size <= HERO_HARD_MAX_BYTES, "The active homepage hero exceeds 250 KB.");

  const shows = JSON.parse(readFile(path.join(ROOT, "data", "shows.json")));
  const checkedCovers = new Set();
  shows.forEach((show) => {
    const relativeCover = String(show?.cover || "").trim();
    if (!relativeCover || checkedCovers.has(relativeCover)) {
      return;
    }
    checkedCovers.add(relativeCover);

    const coverPath = path.resolve(ROOT, relativeCover);
    if (!fs.existsSync(coverPath)) {
      return;
    }

    const coverSize = fs.statSync(coverPath).size;
    assert(
      coverSize <= COVER_HARD_MAX_BYTES,
      `${relativeCover} exceeds the referenced-cover hard limit of 1.5 MB.`,
    );
    if (coverSize > COVER_SOFT_MAX_BYTES) {
      warn(`${relativeCover} exceeds the referenced-cover soft limit of 500 KB (${Math.ceil(coverSize / 1024)} KB).`);
    }

    (Array.isArray(show.coverVariants) ? show.coverVariants : []).forEach((variant) => {
      const width = Number(variant?.width);
      const relativeVariant = String(variant?.src || "").replace(/^\/+/, "");
      assert([320, 640].includes(width), `${show.id} has an unsupported responsive cover width.`);
      assert(relativeVariant.startsWith("images/generated/covers/"), `${show.id} has a responsive cover outside the generated directory.`);
      const variantPath = path.resolve(ROOT, relativeVariant);
      assert(fs.existsSync(variantPath), `${show.id} is missing ${relativeVariant}.`);
      const variantBudget = width === 320 ? 100 * 1024 : 220 * 1024;
      assert(fs.statSync(variantPath).size <= variantBudget, `${relativeVariant} exceeds its ${width}px budget.`);
    });
  });
}

function checkCatalogArtifacts() {
  assert(fs.existsSync(path.join(ROOT, "catalog-src", "shows", "_order.json")), "catalog-src/shows/_order.json is missing.");
  assert(fs.existsSync(path.join(ROOT, "catalog-src", "collections", "_order.json")), "catalog-src/collections/_order.json is missing.");
  assert(fs.existsSync(path.join(ROOT, "data", "archive-stats.json")), "data/archive-stats.json is missing.");
  assert(fs.existsSync(path.join(ROOT, "data", "search-index.json")), "data/search-index.json is missing.");
  assert(fs.existsSync(path.join(ROOT, "docs", "generated", "catalog-status.md")), "docs/generated/catalog-status.md is missing.");
}

function checkPublicPlaceholderMarkers() {
  const publicPagesDir = path.join(ROOT, "site-src", "pages");
  const disallowedPatterns = [
    { pattern: /TODO before launch/gi, label: "TODO before launch" },
    { pattern: /lorem ipsum/gi, label: "lorem ipsum" },
    { pattern: /under construction/gi, label: "under construction" },
    { pattern: /https?:\/\/example\.com/gi, label: "example.com URL" },
  ];

  listFiles(publicPagesDir, ".html").forEach((filePath) => {
    if (filePath.includes(`${path.sep}maintainer${path.sep}`)) {
      return;
    }

    const contents = readFile(filePath);
    disallowedPatterns.forEach(({ pattern, label }) => {
      pattern.lastIndex = 0;
      assert(!pattern.test(contents), `${path.relative(ROOT, filePath)} still contains launch-facing placeholder content (${label}).`);
    });
  });
}

function main() {
  checkLineBudgets();
  checkArchiveReferences();
  checkGeneratedPages();
  checkGeneratedAssets();
  checkImageBudgets();
  checkCatalogArtifacts();
  checkPublicPlaceholderMarkers();
}

main();
